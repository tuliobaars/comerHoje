#' A synthetic photo with fake GPS, to try the metadata remover
#'
#' Writes a small JPEG (120 x 80 pixels) carrying the kind of metadata a phone adds: a GPS position (fake:
#' 0, 0), camera make and model ("CameraDeTeste", "Modelo-Sintetico"), date and time, orientation, a
#' comment and an IPTC block. It lets you see what [limpar_metadados()] removes without using a personal
#' photo. The bytes live in the R code (no binary file in the package).
#'
#' @param arquivo Path of the JPEG file to write.
#' @return The path of the file, invisibly.
#' @examples
#' f <- foto_exemplo()
#' str(metadados_resumo(f))
#' @export
foto_exemplo <- function(arquivo = tempfile(fileext = ".jpg")) {
  hex <- paste(.FOTO_EXEMPLO_HEX, collapse = "")
  writeBin(as.raw(strtoi(substring(hex, seq(1, nchar(hex), 2), seq(2, nchar(hex), 2)), 16L)), arquivo)
  invisible(arquivo)
}

