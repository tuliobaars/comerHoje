#!/usr/bin/env python3
"""Runs EVERY check of comerHoje and writes docs/verification/last_run.json.
   python3 tools/verificar.py [--preflight]   (--preflight: only check and repair this copy; needs: node + npm, python3 >= 3.8 with playwright/chromium and pillow; no R)
R runs in webR (R 4.6 in WebAssembly, from npm); CI also runs the same tests in real R (testthat, R CMD check).
Before the suites, a preflight checks this copy of the repository against tools/manifesto.json (missing
files; hidden files are put back), removes leftovers that R CMD check trips on (stale man/ pages, future
time stamps), installs node_modules if needed, and says exactly what to run for anything else."""
import json, os, pathlib, re, shutil, socket, subprocess, sys, time, http.server, threading, functools
R = pathlib.Path(__file__).resolve().parents[1]

# ---------------------------------------------------------------- preflight
sys.path.insert(0, str(R / "tools"))
import manifesto, gerar_man  # noqa: E402

def preflight(completo=True):
    problemas, feitos = [], []
    if sys.version_info < (3, 8): problemas.append(f"Python {sys.version.split()[0]}: use Python 3.8 ou mais novo")
    if not shutil.which("node"): problemas.append("node não encontrado: instale Node.js 22 ou mais novo (https://nodejs.org)")
    # 1. is this copy complete? (Finder, some zips and some download tools drop hidden files and even binary files)
    m, faltando, diferentes = manifesto.comparar()
    if m is None:
        problemas.append("tools/manifesto.json ausente: esta cópia é anterior à 2.0.2 ou está incompleta")
    else:
        for o, texto in m["ocultos"].items():            # hidden files: the manifest carries their text, so put them back
            f = R / o
            atual = f.read_text(encoding="utf-8") if f.exists() else None
            if atual == texto: continue
            linhas_suas = {l.strip() for l in (atual or "").splitlines() if l.strip()}
            linhas_repo = {l.strip() for l in texto.splitlines() if l.strip()}
            if atual is None or linhas_suas <= linhas_repo:   # missing, or a subset (e.g. the RStudio/renv default .Rbuildignore)
                f.parent.mkdir(parents=True, exist_ok=True); f.write_text(texto, encoding="utf-8")
                feitos.append(f"{o} {'restaurado' if atual is None else 'completado (o desta cópia era um subconjunto do repositório)'}")
            else:
                problemas.append(f"{o} difere do repositório e tem linhas próprias ({', '.join(sorted(linhas_suas - linhas_repo))[:80]}); "
                                 f"confira com: python3 tools/manifesto.py")
        faltando = [r for r in faltando if r not in m["ocultos"] or not (R / r).exists()]
        if faltando:
            problemas.append(f"{len(faltando)} arquivo(s) do repositório ausentes nesta cópia (a cópia perdeu arquivos):\n        " +
                             "\n        ".join(faltando[:20]) + ("\n        ..." if len(faltando) > 20 else "") +
                             "\n      copie de novo com `git clone` / `git pull` ou `rsync -a origem/ destino/`, ou extraia o zip com `unzip` no Terminal")
        outros = [r for r in diferentes if r not in m["ocultos"]]
        if outros:
            print(f"preflight: {len(outros)} arquivo(s) diferentes do manifesto (edições locais?): {', '.join(outros[:5])}"
                  f"{' ...' if len(outros) > 5 else ''}", flush=True)
    # 2. leftovers of older versions (v1 prototype; inst/html is reserved by R and became inst/standalone in 2.0.1)
    velhos = [f for f in ["R/db.R", "R/solver.R", "global.R", "modules", "inst/html", "inst/extdata/exemplo_com_gps.jpg"] if (R / f).exists()]
    if velhos: problemas.append("restos de versões anteriores: " + ", ".join(velhos) +
                                f"\n      apague: rm -r {' '.join(velhos)}   (num repositório git: git rm -r ...)")
    # 3. man/ pages that roxygen made for code that no longer exists (R CMD check: "Undocumented arguments in linha_de_lote.Rd")
    esperados = {pathlib.Path(k).name for k in gerar_man.gerar() if k.startswith("man/")}
    for rd in sorted((R / "man").glob("*.Rd")):
        if rd.name not in esperados and rd.read_text(encoding="utf-8", errors="replace").startswith("% Generated by roxygen2"):
            rd.unlink(); feitos.append(f"man/{rd.name} removido (página antiga gerada pelo roxygen; a função não é mais documentada)")
    # 4. time stamps in the future (a zip made in UTC and opened in Brasília: R CMD check "future file timestamps")
    agora, futuros = time.time(), 0
    for raiz, dirs, arqs in os.walk(R):
        dirs[:] = [d for d in dirs if d not in {".git", "node_modules", "taiga-design-system"}]
        for a in arqs:
            f = os.path.join(raiz, a)
            try:
                if os.path.getmtime(f) > agora + 60: os.utime(f, None); futuros += 1
            except OSError: pass
    if futuros: feitos.append(f"data de modificação de {futuros} arquivo(s) no futuro ajustada para agora")
    # 5. npm packages (fonts, icons, OCR models, webR for the R tests)
    deps = json.loads((R / "package.json").read_text(encoding="utf-8")).get("devDependencies", {})
    faltam = [d for d in deps if not (R / "node_modules" / d / "package.json").exists()]
    if faltam and not problemas and completo:
        print(f"preflight: faltam pacotes npm ({', '.join(faltam)}).", flush=True)
        if shutil.which("npm"):
            print("preflight: rodando `npm ci --ignore-scripts` (uma vez; baixa ~150 MB)...", flush=True)
            r = subprocess.run(["npm", "ci", "--ignore-scripts"], cwd=R)
            faltam = [d for d in deps if not (R / "node_modules" / d / "package.json").exists()]
            if r.returncode != 0 or faltam: problemas.append("`npm ci --ignore-scripts` falhou: rode-o na raiz do repositório e leia o erro")
        else: problemas.append("npm não encontrado: instale Node.js (traz o npm) e rode `npm ci --ignore-scripts` na raiz")
    # 6. browser tests
    if completo:
        try:
            import playwright  # noqa: F401
        except ImportError:
            problemas.append("Playwright para Python ausente: python3 -m pip install playwright pillow && python3 -m playwright install chromium")
        try:
            import PIL  # noqa: F401
        except ImportError:
            problemas.append("Pillow ausente: python3 -m pip install pillow")
    for f in feitos: print("preflight: corrigido:", f, flush=True)
    if problemas:
        print("\nPREFLIGHT: corrija antes de verificar:")
        for p in problemas: print("  -", p)
        sys.exit(2)
    v = subprocess.run(["node", "--version"], capture_output=True, text=True).stdout.strip()
    print(f"preflight ok: node {v}, Python {sys.version.split()[0]}, {len(deps)} pacotes npm, "
          f"{len(m['arquivos']) if m else '?'} arquivos do manifesto presentes, arquivos ocultos em dia, sem restos de versões antigas\n", flush=True)
preflight(completo="--preflight" not in sys.argv)
if "--preflight" in sys.argv: sys.exit(0)             # only check and repair this copy (e.g. before devtools::check())

def porta_livre():
    s = socket.socket(); s.bind(("127.0.0.1", 0)); p = s.getsockname()[1]; s.close(); return p
porta = porta_livre()
class Silencioso(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
class Servidor(http.server.ThreadingHTTPServer):
    def handle_error(self, request, client_address): pass     # a browser that closes early (broken pipe) is not a failure
srv = Servidor(("127.0.0.1", porta), functools.partial(Silencioso, directory=str(R)))
threading.Thread(target=srv.serve_forever, daemon=True).start()
WEBR = ["node", "tools/webr/run.mjs", "tests/webr/run_all.R", "--mount=R:/pkg/R", "--mount=inst:/pkg/inst", "--mount=tests:/pkg/tests", "--mount=references:/refs"]
RD = ["node", "tools/webr/run.mjs", "tests/webr/check_rd.R", "--mount=R:/pkg/R", "--mount=man:/pkg/man", "--mount=NAMESPACE:/pkg/NAMESPACE",
      "--mount=DESCRIPTION:/pkg/DESCRIPTION", "--mount=tests:/pkg/tests", "--mount=inst/extdata:/pkg/inst/extdata",
      "--mount=inst/standalone:/pkg/inst/standalone", "--mount=inst/quarto:/pkg/inst/quarto"]
PY = sys.executable                                  # the same Python (with Playwright) for every suite
SUITES = [
    ("build: 3 entregas a partir de srcjs/", ["node", "tools/build.mjs", "--html-ocr"], r"HTML: inst/standalone/comerhoje\.html (\d+ KB)"),
    ("JS: núcleo contra as fixtures", ["node", "tests/js/run_golden.js"], r"(\d+) ok"),
    ("Leitor embutido no HTML: node = R (fixture)", ["node", "tests/js/test_com_leitor.mjs"], r"(\d+) ok"),
    ("Apps Script da planilha (simulado)", ["node", "tests/js/test_apps_script.js"], r"(\d+) ok"),
    ("R no webR: mesmas fixtures + paridade", WEBR, r"(\d+) expectativas ok"),
    ("R CMD check no webR: Rd, usage, exemplos, ASCII", RD, r"(\d+) exemplos rodaram"),
    ("Código R só com ASCII (R CMD check)", [PY, "tools/r_ascii.py", "--verificar"], r"(\d+) arquivos"),
    ("Tarball do R CMD build (simulado)", [PY, "tools/simular_tarball.py"], r"(\d+) arquivos no tarball"),
    ("man/ e NAMESPACE em dia com o roxygen", [PY, "tools/gerar_man.py", "--verificar"], r"\((\d+) arquivos"),
    ("SQLite: SQL do repo_sqlite x esquema", [PY, "tests/sql/test_sqlite.py"], r"(\d+) verificações ok"),
    ("HTML + Quarto: 2 estilos x 2 temas x 3 tamanhos", [PY, "tests/e2e/test_html.py"], r"(\d+) verificações ok"),
    ("Contraste WCAG (tokens renderizados)", [PY, "tests/e2e/test_contraste.py"], r"(\d+/\d+) pares"),
    ("Protocolo Shiny com R real (webR)", [PY, "tests/e2e/test_protocolo_shiny.py"], r"(\d+) verificações ok"),
    ("Leitura da validade no aparelho (fotos)", [PY, "tests/e2e/test_leitura.py"], r"()"),
]
res = []
for nome, cmd, padrao in SUITES:
    t0 = time.time()
    env = {**__import__("os").environ, "COMERHOJE_BANCADA": f"http://127.0.0.1:{porta}"}
    p = subprocess.run(cmd, cwd=R, capture_output=True, text=True, env=env, timeout=3600)
    saida = p.stdout + p.stderr
    m = re.search(padrao, saida)
    falha = p.returncode != 0 or "FALHOU" in saida or "R ERROR" in saida
    res.append({"suite": nome, "ok": not falha, "resumo": (m.group(1) if m and m.group(1) else ("ver saída" if falha else "ok")), "s": round(time.time() - t0, 1),
                "cauda": saida.strip().splitlines()[-25:] if falha else None})
    print(f"{'OK ' if not falha else 'XX '} {nome:52s} {res[-1]['resumo']:>12s} {res[-1]['s']:6.1f} s", flush=True)
    if falha: print("\n".join(res[-1]["cauda"]))
# reference photos: no GPS left (the metadata remover ran over them)
from PIL import Image
gps = {f.name: len(Image.open(f).getexif().get_ifd(0x8825)) for f in sorted((R / "references").glob("*.jp*g"))}
res.append({"suite": "Fotos de referência sem GPS", "ok": all(v == 0 for v in gps.values()), "resumo": f"{sum(v == 0 for v in gps.values())}/{len(gps)}", "s": 0})
print(f"{'OK ' if res[-1]['ok'] else 'XX '} {res[-1]['suite']:52s} {res[-1]['resumo']:>12s}")
# relative links in the documents
quebrados = []
for md in [R / "README.md", R / "NEWS.md", *sorted((R / "docs").glob("*.md"))]:
    if not md.exists(): continue
    txt = md.read_text(encoding="utf-8")
    for alvo in re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", txt):
        if re.match(r"https?:|mailto:", alvo): continue
        if not (md.parent / alvo).exists() and not alvo.endswith("verification/last_run.json"):   # written by this script
            quebrados.append(f"{md.name}: {alvo}")
res.append({"suite": "Links relativos nos documentos", "ok": not quebrados, "resumo": f"{len(quebrados)} quebrados", "s": 0, "cauda": quebrados or None})
print(f"{'OK ' if res[-1]['ok'] else 'XX '} {res[-1]['suite']:52s} {res[-1]['resumo']:>12s}")
for q in quebrados: print("     link quebrado:", q)
srv.shutdown()
versoes = {k: (subprocess.run(c, capture_output=True, text=True).stdout.strip().splitlines() or ["?"])[0] for k, c in {"node": ["node", "--version"], "python": [sys.executable, "--version"]}.items()}
(R / "docs/verification").mkdir(parents=True, exist_ok=True)
(R / "docs/verification/last_run.json").write_text(json.dumps({"quando": time.strftime("%Y-%m-%d %H:%M:%S %z"), "versoes": versoes, "suites": res}, ensure_ascii=False, indent=1), encoding="utf-8")
n = sum(r["ok"] for r in res)
print(f"\n{n}/{len(res)} suítes ok")
sys.exit(0 if n == len(res) else 1)
