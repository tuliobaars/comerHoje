#!/usr/bin/env python3
"""Mini-roxygen: writes man/*.Rd and NAMESPACE from the roxygen comments in R/*.R.

The canonical tool is roxygen2 (`devtools::document()` or `roxygen2::roxygenise()`); this script
exists so that the package ships complete documentation even where R is not available (the CI
sandbox runs R only as webR). It understands the subset of roxygen used in this package:

  title / description / details paragraphs, @param (also "a,b"), @inheritParams, @return,
  @examples, @seealso, @keywords, @export, @noRd, "_PACKAGE";
  markdown: `code`, [fun()], [pkg::fun()], **bold**, "- " bullet lists.

Usage:  python3 tools/gerar_man.py            # writes man/ and NAMESPACE
        python3 tools/gerar_man.py --verificar  # exit 1 if man/ or NAMESPACE would change
"""
import pathlib
import re
import sys

RAIZ = pathlib.Path(__file__).resolve().parents[1]
CABECALHO = "% Generated by roxygen2: do not edit by hand\n"
TAGS = {"param", "inheritParams", "return", "examples", "seealso", "keywords", "export", "noRd", "details"}


# ---------------------------------------------------------------- parsing
def blocos(arquivo):
    """Yields (lines of the roxygen block, object name, formals text) for each documented object."""
    linhas = arquivo.read_text(encoding="utf-8").split("\n")
    i = 0
    while i < len(linhas):
        if not linhas[i].startswith("#'"):
            i += 1
            continue
        ini = i
        while i < len(linhas) and linhas[i].startswith("#'"):
            i += 1
        bloco = [re.sub(r"^#' ?", "", l) for l in linhas[ini:i]]
        alvo = linhas[i] if i < len(linhas) else ""
        if alvo.strip() == '"_PACKAGE"':
            yield bloco, "_PACKAGE", None
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_.]*) <- function\(", alvo)
        if not m:
            raise SystemExit(f"{arquivo.name}:{i + 1}: bloco roxygen sem função logo abaixo")
        # formals: from the "(" after "function" to the matching ")"
        resto = "\n".join(linhas[i:])
        p = resto.index("function(") + len("function(")
        nivel, j, aspas = 1, p, None
        while nivel:
            c = resto[j]
            if aspas:
                if c == "\\":
                    j += 1
                elif c == aspas:
                    aspas = None
            elif c in "\"'":
                aspas = c
            elif c in "([{":
                nivel += 1
            elif c in ")]}":
                nivel -= 1
            j += 1
        yield bloco, m.group(1), resto[p:j - 1]


def separar_virgulas(txt):
    """Splits at top-level commas (outside parentheses and strings)."""
    partes, nivel, aspas, atual = [], 0, None, ""
    for k, c in enumerate(txt):
        if aspas:
            atual += c
            if c == aspas and txt[k - 1] != "\\":
                aspas = None
            continue
        if c in "\"'":
            aspas = c
        elif c in "([{":
            nivel += 1
        elif c in ")]}":
            nivel -= 1
        if c == "," and nivel == 0:
            partes.append(atual)
            atual = ""
        else:
            atual += c
    if atual.strip():
        partes.append(atual)
    return [re.sub(r"\s+", " ", p).strip() for p in partes]


def analisar(bloco):
    """Returns dict: paragraphs (list of str), tags (list of (tag, text))."""
    cab, tags, atual = [], [], None
    for l in bloco:
        m = re.match(r"^@(\w+)\s?(.*)$", l)
        if m and m.group(1) in TAGS:
            atual = [m.group(1), m.group(2)]
            tags.append(atual)
        elif m:
            raise SystemExit(f"tag roxygen não suportada: @{m.group(1)}")
        elif atual is None:
            cab.append(l)
        else:
            atual[1] += "\n" + l
    paragrafos, p = [], []
    for l in cab + [""]:
        if l.strip():
            p.append(l)
        elif p:
            paragrafos.append("\n".join(p))
            p = []
    return paragrafos, [(t, x.strip("\n")) for t, x in tags]


# ---------------------------------------------------------------- markdown -> Rd
def esc(s):
    return s.replace("\\", "\\\\").replace("%", "\\%").replace("{", "\\{").replace("}", "\\}")


def inline(s):
    out, pos = [], 0
    padrao = re.compile(r"`([^`]+)`|\[([A-Za-z0-9_.]+::)?([A-Za-z0-9_.]+)\(\)\]|\*\*([^*]+)\*\*")
    for m in padrao.finditer(s):
        out.append(esc(s[pos:m.start()]))
        if m.group(1) is not None:
            out.append("\\code{" + esc(m.group(1)) + "}")
        elif m.group(3) is not None:
            pkg, fn = m.group(2), m.group(3)
            if pkg:
                out.append("\\code{\\link[%s:%s]{%s%s()}}" % (pkg[:-2], fn, pkg, fn))
            else:
                out.append("\\code{\\link[=%s]{%s()}}" % (fn, fn))
        else:
            out.append("\\strong{" + esc(m.group(4)) + "}")
        pos = m.end()
    out.append(esc(s[pos:]))
    return "".join(out)


def texto(s):
    """A text section (may contain several paragraphs and bullet lists)."""
    saida, lista = [], None
    for par in re.split(r"\n\s*\n", s.strip()):
        linhas = par.split("\n")
        if all(re.match(r"^\s*- ", l) or (l.startswith("  ") and k) for k, l in enumerate(linhas)):
            itens = []
            for l in linhas:
                if re.match(r"^\s*- ", l):
                    itens.append(re.sub(r"^\s*- ", "", l))
                else:
                    itens[-1] += " " + l.strip()
            saida.append("\\itemize{\n" + "\n".join("\\item " + inline(x) for x in itens) + "\n}")
        else:
            saida.append(inline("\n".join(l.strip() for l in linhas)))      # keeps the source line breaks, like roxygen2
    return "\n\n".join(saida)


def uso(nome, formais):
    args = separar_virgulas(formais) if formais.strip() else []
    uma = "%s(%s)" % (nome, ", ".join(args))
    if len(uma) <= 80:
        return esc_uso(uma)
    return esc_uso("%s(\n%s\n)" % (nome, ",\n".join("  " + a for a in args)))


def esc_uso(s):
    return s.replace("\\", "\\\\").replace("%", "\\%")


def esc_exemplos(s):
    return s.replace("%", "\\%")     # \dontrun{} and friends pass through, like roxygen2


# ---------------------------------------------------------------- main
def gerar():
    desc = (RAIZ / "DESCRIPTION").read_text(encoding="utf-8")
    docs, exports, params_de = {}, [], {}
    for arq in sorted((RAIZ / "R").glob("*.R")):
        for bloco, nome, formais in blocos(arq):
            paragrafos, tags = analisar(bloco)
            if any(t == "noRd" for t, _ in tags):
                continue
            if any(t == "export" for t, _ in tags):
                exports.append(nome)
            params = {}
            for t, x in tags:
                if t == "param":
                    n, _, d = x.partition(" ")
                    params[n] = d.strip()
            params_de[nome] = params
            docs[nome] = (arq.name, paragrafos, tags, formais, params)

    arquivos = {}
    for nome, (arq, paragrafos, tags, formais, params) in docs.items():
        formais_lst = [re.split(r"\s*=", a)[0].strip() for a in separar_virgulas(formais)] if formais and formais.strip() else []
        for t, x in tags:
            if t == "inheritParams":
                for k, v in params_de[x.strip()].items():
                    if all(n.strip() in formais_lst for n in k.split(",")):
                        params.setdefault(k, v)
        rd_nome = "comerHoje-package" if nome == "_PACKAGE" else nome
        partes = [CABECALHO + "%% Please edit documentation in R/%s\n" % arq]
        if nome == "_PACKAGE":
            partes.append("\\docType{package}\n\\name{comerHoje-package}\n\\alias{comerHoje}\n\\alias{comerHoje-package}\n")
        else:
            partes.append("\\name{%s}\n\\alias{%s}\n" % (nome, nome))
        partes.append("\\title{%s}\n" % inline(" ".join(paragrafos[0].split())))
        if nome != "_PACKAGE":
            partes.append("\\usage{\n%s\n}\n" % uso(nome, formais))
            nomes_formais = [re.split(r"\s*=", a)[0].strip() for a in separar_virgulas(formais)] if formais.strip() else []
            cobertos = []
            for k in params:
                cobertos += [x.strip() for x in k.split(",")]
            faltam = [a for a in nomes_formais if a not in cobertos]
            sobram = [a for a in cobertos if a not in nomes_formais]
            if faltam or sobram:
                raise SystemExit(f"{nome}: @param faltando {faltam} / sobrando {sobram}")
            if params:
                ordem = sorted(params, key=lambda k: nomes_formais.index(k.split(",")[0].strip()))
                itens = "\n\n".join("\\item{%s}{%s}" % (", ".join(x.strip() for x in k.split(",")), texto(params[k])) for k in ordem)
                partes.append("\\arguments{\n%s\n}\n" % itens)
            ret = [x for t, x in tags if t == "return"]
            if not ret:
                raise SystemExit(f"{nome}: sem @return")
            partes.append("\\value{\n%s\n}\n" % texto(ret[0]))
        descricao = paragrafos[1] if len(paragrafos) > 1 else paragrafos[0]
        partes.append("\\description{\n%s\n}\n" % texto(descricao if nome != "_PACKAGE" else "\n\n".join(paragrafos[1:])))
        detalhes = [x for t, x in tags if t == "details"] or (["\n\n".join(paragrafos[2:])] if len(paragrafos) > 2 and nome != "_PACKAGE" else [])
        if detalhes:
            partes.append("\\details{\n%s\n}\n" % texto(detalhes[0]))
        ex = [x for t, x in tags if t == "examples"]
        for l in (ex[0].split("\n") if ex else []) + uso(nome, formais).split("\n") if nome != "_PACKAGE" else []:
            if len(l) > 100:                    # R CMD check: "Rd files with lines wider than 100 characters"
                raise SystemExit(f"{nome}: linha de exemplo/uso com {len(l)} caracteres (máx. 100): {l[:60]}...")
        if ex:
            partes.append("\\examples{\n%s\n}\n" % esc_exemplos(ex[0].strip("\n")))
        ver = [x for t, x in tags if t == "seealso"]
        if nome == "_PACKAGE":
            autor = re.search(r'person\("([^"]+)",\s*"([^"]+)".*?email\s*=\s*"([^"]+)"', desc)
            partes.append("\\author{\n\\strong{Maintainer}: %s %s \\email{%s}\n}\n" % autor.groups())
        if ver:
            partes.append("\\seealso{\n%s\n}\n" % texto(ver[0]))
        for t, x in tags:
            if t == "keywords":
                for k in x.split():
                    partes.append("\\keyword{%s}\n" % k)
        arquivos["man/%s.Rd" % rd_nome] = "".join(partes)

    ns = "# Generated by roxygen2: do not edit by hand\n\n" + "".join("export(%s)\n" % e for e in sorted(exports, key=lambda s: s.encode()))
    arquivos["NAMESPACE"] = ns
    return arquivos


def main():
    arquivos = gerar()
    verificar = "--verificar" in sys.argv
    diferentes = []
    existentes = {str(p.relative_to(RAIZ)) for p in (RAIZ / "man").glob("*.Rd")} if (RAIZ / "man").exists() else set()
    for caminho, conteudo in arquivos.items():
        p = RAIZ / caminho
        if not p.exists() or p.read_text(encoding="utf-8") != conteudo:
            diferentes.append(caminho)
            if not verificar:
                p.parent.mkdir(exist_ok=True)
                p.write_text(conteudo, encoding="utf-8")
    orfaos = sorted(existentes - set(arquivos))
    if verificar:
        if diferentes or orfaos:
            print("man/ ou NAMESPACE desatualizados:", ", ".join(diferentes + orfaos))
            print("rode: python3 tools/gerar_man.py   (ou devtools::document())")
            sys.exit(1)
        print(f"man/ e NAMESPACE em dia ({len(arquivos) - 1} arquivos .Rd)")
        return
    for o in orfaos:
        (RAIZ / o).unlink()
    print(f"{len(arquivos) - 1} arquivos .Rd e NAMESPACE ({len(diferentes)} alterados, {len(orfaos)} removidos)")


if __name__ == "__main__":
    main()
